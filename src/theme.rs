use ratatui::style::Color;

#[derive(Debug, Clone)]
pub struct Theme {
    pub name: String,
    pub bg: Color,
    pub fg: Color,
    pub selected_bg: Color,
    pub selected_fg: Color,
    pub dir_fg: Color,
    pub file_fg: Color,
    pub border: Color,
    pub title: Color,
    pub status_bg: Color,
    pub status_fg: Color,
    pub preview_bg: Color,
    pub preview_fg: Color,
    pub editor_bg: Color,
    pub error_fg: Color,
    pub menu_bg: Color,
    pub menu_fg: Color,
    pub menu_selected_bg: Color,
    pub menu_selected_fg: Color,
    pub menu_hotkey_fg: Color,
    pub separator_fg: Color,
    pub palette_bg: Color,
    pub palette_fg: Color,
    pub palette_selected_bg: Color,
    pub palette_selected_fg: Color,
}

impl Theme {
    pub fn from_name(name: &str) -> Option<Self> {
        match name {
            "tokyo-night" => Some(tokyo_night()),
            "dracula" => Some(dracula()),
            "nord" => Some(nord()),
            "solarized-dark" => Some(solarized_dark()),
            "catppuccin-mocha" => Some(catppuccin_mocha()),
            "one-dark" => Some(one_dark()),
            "monokai" => Some(monokai()),
            "gruvbox-dark" => Some(gruvbox_dark()),
            _ => None,
        }
    }

    pub fn all_names() -> Vec<String> {
        vec![
            "tokyo-night".to_string(),
            "dracula".to_string(),
            "nord".to_string(),
            "solarized-dark".to_string(),
            "catppuccin-mocha".to_string(),
            "one-dark".to_string(),
            "monokai".to_string(),
            "gruvbox-dark".to_string(),
        ]
    }
}

fn rgb(r: u8, g: u8, b: u8) -> Color {
    Color::Rgb(r, g, b)
}

